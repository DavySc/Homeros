-- Writes src/tools/icons.inc: mini.icons' glyphs (my-nvim's mini.nvim at
-- db41c40) for the names and extensions mini.icons and Neovim's filetype
-- tables know.  nvim --clean --headless -l icons.lua MINI_DIR OUT
vim.opt.rtp:prepend(arg[1])
require("mini.icons").setup()
local function upv(f, want)
  for i = 1, 200 do
    local n, v = debug.getupvalue(f, i)
    if not n then return end
    if n == want then return v end
  end
end
local function keys(...)
  local set = {}
  for _, t in ipairs({ ... }) do
    for k, v in pairs(t) do set[type(k) == "string" and k or v] = true end
  end
  local r = vim.tbl_keys(set)
  table.sort(r)
  return r
end
local function c(s) return '"' .. s:gsub('[\\"]', "\\%0") .. '"' end
local out = assert(io.open(arg[2], "w"))
out:write("/* Generated by src/tools/conform/icons.lua from mini.icons; sorted for bsearch. */\n")
local function tbl(name, list, cat)
  out:write(("static const Icon %s[] = {\n"):format(name))
  local n = 0
  for _, k in ipairs(list) do
    local icon, _, is_default = MiniIcons.get(cat, k)
    if not is_default then out:write(("\t{ %s, %s },\n"):format(c(k), c(icon))); n = n + 1 end
  end
  out:write("};\n")
  return n
end
-- Neovim's filename patterns that name whole files ("[mM]akefile$",
-- "^%.bashrc"): each spelled out, so its icon comes from the same match
local function spell(p)
  p = p:gsub("^%^", ""):gsub("%$$", ""):gsub("%%%.", ".")
  if p:find("[^%w%._%-%[%]]") or p:find("%[%^") then return {} end
  local out, i = { "" }, 1
  while i <= #p do
    local alts
    if p:sub(i, i) == "[" then
      local j = p:find("]", i, true)
      if not j then return {} end
      alts = {}
      for ch in p:sub(i + 1, j - 1):gmatch(".") do alts[#alts + 1] = ch end
      i = j + 1
    else
      alts = { p:sub(i, i) }
      i = i + 1
    end
    local nxt = {}
    for _, o in ipairs(out) do for _, a in ipairs(alts) do nxt[#nxt + 1] = o .. a end end
    out = nxt
    if #out > 16 then return {} end
  end
  return out
end
local names = {}
for k, v in pairs(upv(vim.filetype.add, "pattern")) do
  for kk in pairs(type(v) == "table" and v or { [k] = true }) do
    local key = type(v) == "table" and kk or k
    if type(key) == "string" and not key:find("/") then for _, nm in ipairs(spell(key)) do if nm ~= "" then names[#names + 1] = nm end end end
  end
end
local dirs = tbl("dir_icons", keys(MiniIcons.list("directory")), "directory")
local files = tbl("file_icons", keys(MiniIcons.list("file"), upv(vim.filetype.match, "filename"), names), "file")
local ext = {}
for _, k in ipairs(keys(MiniIcons.list("extension"), upv(vim.filetype.match, "extension"))) do ext[#ext + 1] = k:lower() end
ext = keys(ext)
local exts = tbl("ext_icons", ext, "extension")
out:write(("static const char icon_dir[] = %s, icon_file[] = %s;\n"):format(c(MiniIcons.get("default", "directory")), c(MiniIcons.get("default", "file"))))
out:close()
print(dirs, files, exts)
