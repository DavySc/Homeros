#!/usr/bin/env python3
"""Generate src/uni/tab.h from the Unicode Character Database.

usage: gen.py UCD_DIR > src/uni/tab.h

UCD_DIR holds UnicodeData.txt, GraphemeBreakProperty.txt, emoji-data.txt,
DerivedCoreProperties.txt and EastAsianWidth.txt of one version (here 18.0.0,
from github.com/unicode-org/unicodetools, unicodetools/data/ucd/18.0.0/).
The properties are those Neovim 0.12 takes from utf8proc; where utf8proc or
Neovim depart from the plain UCD reading, the rule says so.  test_uni_nvim.c
compares the result with Neovim on every code point.
"""
import hashlib, os, sys

FILES = ['UnicodeData.txt', 'GraphemeBreakProperty.txt', 'emoji-data.txt',
         'DerivedCoreProperties.txt', 'EastAsianWidth.txt']
GCB = {'Control': 1, 'CR': 1, 'LF': 1,  # CR and LF are ASCII, which never joins (uni.c)
       'Extend': 2, 'L': 3, 'V': 4, 'T': 5, 'LV': 6, 'LVT': 7, 'Regional_Indicator': 8,
       'SpacingMark': 9, 'Prepend': 10, 'ZWJ': 11}
EP, RI = 12, 8
INCB = {'Linker': 1, 'Consonant': 2, 'Extend': 3}
# Neovim's utf_printable() (mbyte.c): shown as <xxxx>, 6 cells
NONPRINT = [(0x070F, 0x070F), (0x180B, 0x180E), (0x200B, 0x200F), (0x202A, 0x202E),
            (0x2060, 0x206F), (0xD800, 0xDFFF), (0xFEFF, 0xFEFF), (0xFFF9, 0xFFFB), (0xFFFE, 0xFFFF)]
# utf8proc's charwidth is 0 for these categories, so Neovim never makes them wide
ZEROW = {'Mn', 'Me', 'Cf', 'Zl', 'Zp', 'Cc', 'Cs'}
N = 0x110000


def ranges(path, keep=lambda v: True):
    out = {}
    for line in open(path, encoding='utf-8'):
        line = line.split('#')[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(';')]
        a, _, b = f[0].partition('..')
        a = int(a, 16)
        b = int(b, 16) if b else a
        if keep(f[1:]):
            for c in range(a, b + 1):
                out[c] = f[1:]
    return out


def props(d):
    cat, first = {}, None
    for line in open(os.path.join(d, 'UnicodeData.txt'), encoding='utf-8'):
        f = line.split(';')
        c = int(f[0], 16)
        if f[1].endswith('First>'):
            first = c
        elif f[1].endswith('Last>'):
            for x in range(first, c + 1):
                cat[x] = f[2]
        else:
            cat[c] = f[2]
    gcb = ranges(os.path.join(d, 'GraphemeBreakProperty.txt'))
    ep = ranges(os.path.join(d, 'emoji-data.txt'), lambda v: v[0] == 'Extended_Pictographic')
    icb = ranges(os.path.join(d, 'DerivedCoreProperties.txt'), lambda v: v[0] == 'InCB')
    eaw = ranges(os.path.join(d, 'EastAsianWidth.txt'))
    p = bytearray(N)
    for c in range(N):
        bc, ic, cells = 0, 0, 0
        if c in cat:  # utf8proc gives unassigned code points the defaults
            bc = GCB.get(gcb.get(c, ['Other'])[0], 0)
            if bc == 0 and c in ep:
                bc = EP
            ic = INCB.get(icb[c][1], 0) if c in icb else 0
            w = eaw.get(c, ['N'])[0]
            # utf_char2cells(): wide, or an emoji from U+1F000 on that is not ambiguous
            if (w in ('W', 'F') and cat[c] not in ZEROW) or (c >= 0x1F000 and w != 'A' and bc in (EP, RI)):
                cells = 1
        if c < 0x80:  # reached only by an overlong sequence, which Neovim shows as the ASCII
            cells = 2 if c == 0 else 1 if c < 0x20 or c == 0x7F else 0  # character (<00>, ^X; a tab as ^I)
        if 0x80 <= c <= 0x9F:  # not in 'isprint': <xx>, 4 cells
            cells = 2
        if any(a <= c <= b for a, b in NONPRINT):
            cells = 3
        p[c] = bc + 16 * ic + 64 * cells
    return p


def main():
    d = sys.argv[1]
    p = props(d)
    B = 128  # the smallest block size whose distinct blocks fit an unsigned char index
    blocks, t1 = {}, []
    for k in range(N // B):
        blk = bytes(p[k * B:(k + 1) * B])
        t1.append(blocks.setdefault(blk, len(blocks)))
    assert len(blocks) <= 256, len(blocks)
    w = sys.stdout.write
    w('/* Generated by src/uni/gen.py from the Unicode Character Database; do not edit.\n')
    for f in FILES:
        w('   %s sha256 %s\n' % (f, hashlib.sha256(open(os.path.join(d, f), 'rb').read()).hexdigest()))
    w('   Property byte: Grapheme_Cluster_Break class + 16 * InCB + 64 * cells code (uni.c). */\n')
    w('#define UNI_B %d\n' % B)
    w('static const unsigned char uni_t1[%d] = {\n' % len(t1))
    for k in range(0, len(t1), 24):
        w(','.join(str(x) for x in t1[k:k + 24]) + ',\n')
    w('};\n')
    w('/* %d distinct blocks; the rest are zero so that any index is in bounds */\n' % len(blocks))
    w('static const unsigned char uni_t2[256][UNI_B] = {\n')
    for blk in blocks:
        w('{' + ','.join(str(x) for x in blk) + '},\n')
    w('};\n')


if __name__ == '__main__':
    main()
