"""Writes tests/test_org.c: fixed org texts and what Org's parser
(oracle.el, Emacs 31.1) makes of them, recorded, so `make test` checks them
without Emacs.  python3 src/org/oracle/record.py EMACS > tests/test_org.c"""
import subprocess, sys, os, tempfile

CASES = [
    # the design's reduced cases (DESIGN.md, Org): orgize 0.9 loses the drawer under any repeater
    ("habit +1d", "* TODO Water\nSCHEDULED: <2026-11-22 Mon +1d>\n:PROPERTIES:\n:STYLE: habit\n:END:\n"),
    ("habit ++1w", "* TODO Water\nSCHEDULED: <2026-11-22 Mon ++1w>\n:PROPERTIES:\n:STYLE: habit\n:END:\n"),
    ("habit .+1d", "* TODO Water\nSCHEDULED: <2026-11-22 Mon .+1d>\n:PROPERTIES:\n:STYLE: habit\n:END:\n"),
    # orgize 0.10 loses the drawer under a habit's .+1d/3d, and tables under affiliated keywords
    ("habit .+1d/3d", "* TODO Water\nSCHEDULED: <2026-11-22 Mon .+1d/3d>\n:PROPERTIES:\n:STYLE: habit\n:END:\n"),
    ("#+NAME table", "#+NAME: t\n| a | b |\n|---+---|\n| 1 | 2 |\n"),
    ("#+CAPTION table", "#+CAPTION: c\n| a |\n"),
    ("#+TBLNAME table", "#+TBLNAME: t\n| a |\n"),
    ("#+ATTR_HTML table", "#+ATTR_HTML: :border 2\n| a |\n"),
    # found by the oracle while building this package
    ("tags keep inner empties", "*** x ::y:\n"),
    ("tab counts 8 in list indentation", "\t- tag :: x\n \t:MyDrawer:\n/a/\n"),
    ("planning repeater is case-sensitive", "* H\nSCHEDULED: <2026-11-22 Sun +1D> DEADLINE: <2026-11-23 Mon -2d>\n"),
    ("lowercase planning keyword", "* H\nscheduled: <2026-11-22 Sun>\n"),
    ("#+TBLFM past the item", "- | a |\n#+TBLFM: x\n"),
    ("clock and logbook", "* DONE [#B] Task :work:\nCLOSED: [2026-11-01 Sun 11:00]\n:LOGBOOK:\nCLOCK: [2026-11-01 Sun 10:00]--[2026-11-01 Sun 11:30] =>  1:30\nCLOCK: [2026-11-02 Mon 9:00]\n:END:\n"),
    ("blocks", "#+BEGIN_SRC python :results output\nprint(1)\n#+END_SRC\n\n#+begin_quote\nq\n#+end_quote\n#+BEGIN_foo x\n#+END_foo\n#+BEGIN_SRC c\nunclosed\n"),
    ("lists", "- a\n  - [X] b\n  - [x] c\n1. [@3] d\n\n\n- e\n"),
    ("ordered item with ::", "1. tag :: x\n- tag :: y\n"),
    ("footnotes", "[fn:1] one\n\n\n[fn:2] two\n#+NAME: n\n[fn:3]\n"),
    ("first section", "  \n# comment\n:PROPERTIES:\n:ID: x\n:END:\ntext\n* H\n"),
    ("table.el", "+---+---+\n| a | b |\n+---+---+\n"),
    ("misc", "-----\n: fixed\n%%(diary)\n\\begin{equation}\nx\n\\end{equation}\n#+CALL: f()\n#+TITLE: t\n"),
    ("nested headlines", "* a\n** b\n*** c\n** d\n* e\n\n"),
    ("no final newline", "* a\nb"),
    ("empty", ""),
]

emacs = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
with tempfile.TemporaryDirectory() as d:
    files = []
    for i, (_, text) in enumerate(CASES):
        f = os.path.join(d, '%02d.org' % i)
        open(f, 'w', encoding='utf-8', newline='').write(text)
        files.append(f)
    out = subprocess.run([emacs, '-Q', '--batch', '-l', os.path.join(here, 'oracle.el')] + files,
                         capture_output=True, text=True, check=True).stdout
want = out.split('== ')[1:]

def c(s):
    return '"' + s.encode('unicode_escape').decode().replace('"', '\\"') + '"'

print('''/* The org parser against what Org's own parser makes of fixed texts:
   the design's reduced cases and the cases the oracle found.  Generated by
   src/org/oracle/record.py from Emacs 31.1; do not edit. */
#define NO_MAIN
#include "../src/org/oracle/dump.c"
#include "check.h"

static const struct { const char *name, *text, *want; } C[] = {''')
for (name, text), w in zip(CASES, want):
    lines = w.split('\n', 1)[1]
    print('\t{ %s, %s,\n\t  %s },' % (c(name), c(text), c(lines)))
print('''};

int main(void)
{
	for (size_t i = 0; i < sizeof C / sizeof *C; i++) {
		char *got = NULL;
		size_t n = 0;
		FILE *f = open_memstream(&got, &n);
		Text *t = text_new(C[i].text, strlen(C[i].text));
		Org *o = org_new(t);
		CHECK(f && t && o);
		print(f, t, o, C[i].text);
		fclose(f);
		if (strcmp(got, C[i].want)) fprintf(stderr, "%s:\\nwant:\\n%sgot:\\n%s", C[i].name, C[i].want, got);
		CHECK(!strcmp(got, C[i].want));
		free(got); org_free(o); text_free(t);
	}
	return 0;
}''')
